import { createWriteStream } from "node:fs";
import { writeFile } from "node:fs/promises";
import type { Timesheet } from "@deep/shared";
import PDFDocument from "pdfkit";
import { timesheetCsv } from "./insights-core";

const hours = (min: number) => (min / 60).toFixed(2);
const money = (n: number | null) => (n === null ? "" : n.toFixed(2));

export async function writeTimesheet(
	t: Timesheet,
	format: "csv" | "pdf",
	path: string,
	title: string,
) {
	if (format === "csv") {
		await writeFile(path, timesheetCsv(t), "utf8");
		return;
	}
	await writePdf(t, path, title);
}

/** A plain, printable A4 timesheet. */
function writePdf(t: Timesheet, path: string, title: string): Promise<void> {
	return new Promise((resolve, reject) => {
		const doc = new PDFDocument({ size: "A4", margin: 48 });
		const out = createWriteStream(path);
		out.on("finish", () => resolve());
		out.on("error", reject);
		doc.on("error", reject);
		doc.pipe(out);

		const left = doc.page.margins.left;
		const width = doc.page.width - left - doc.page.margins.right;
		const cols = [
			{ label: "Date", w: 70, align: "left" as const },
			{ label: "Project", w: 95, align: "left" as const },
			{ label: "Task", w: width - 70 - 95 - 55 - 75, align: "left" as const },
			{ label: "Hours", w: 55, align: "right" as const },
			{ label: "Amount", w: 75, align: "right" as const },
		];

		doc
			.font("Helvetica-Bold")
			.fontSize(20)
			.fillColor("#111")
			.text("Timesheet", left, 48);
		doc.font("Helvetica").fontSize(11).fillColor("#555").text(title);
		doc.text(`${t.from} to ${t.to}`);
		doc.moveDown(1.2);

		const row = (values: string[], bold = false, shade = false) => {
			const y = doc.y;
			if (y > doc.page.height - 80) {
				doc.addPage();
			}
			const top = doc.y;
			if (shade)
				doc
					.rect(left, top - 3, width, 18)
					.fill("#f2f2f4")
					.fillColor("#111");
			let x = left;
			doc
				.font(bold ? "Helvetica-Bold" : "Helvetica")
				.fontSize(9.5)
				.fillColor("#111");
			let lineHeight = 0;
			values.forEach((v, i) => {
				const c = cols[i]!;
				doc.text(v, x + 2, top, { width: c.w - 4, align: c.align });
				lineHeight = Math.max(
					lineHeight,
					doc.heightOfString(v, { width: c.w - 4 }),
				);
				x += c.w;
			});
			doc.y = top + Math.max(14, lineHeight) + 4;
		};

		row(
			cols.map((c) => c.label),
			true,
			true,
		);
		for (const r of t.rows) {
			row([r.date, r.project, r.task, hours(r.minutes), money(r.amount)]);
		}
		doc
			.moveTo(left, doc.y)
			.lineTo(left + width, doc.y)
			.strokeColor("#999")
			.stroke();
		doc.moveDown(0.4);
		row(["Total", "", "", hours(t.totalMinutes), money(t.totalAmount)], true);

		doc
			.moveDown(2)
			.font("Helvetica")
			.fontSize(8)
			.fillColor("#888")
			.text(
				`Generated by Deep on ${new Date().toISOString().slice(0, 10)}. Hours are focused time from tracked sessions.`,
				left,
			);
		doc.end();
	});
}
